#!/usr/bin/env sh
# gen-secrets.sh — writes infrastructure/eval/.env (gitignored, mode 600),
# refusing to overwrite an existing one unless FORCE=1.
#
# Writes:
#   POSTGRES_PASSWORD     — the eval superuser password (compose needs it)
#   AUTHENTICATOR_PASSWORD — the NOBYPASSRLS role PostgREST connects as
#   JWT_SECRET            — 32 random bytes, hex
#   ANON_KEY              — HS256 JWT, role "anon"
#   SERVICE_ROLE_KEY      — HS256 JWT, role "service_role"
#
# The two keys are HS256 JWTs signed with JWT_SECRET, exactly like the live
# grobase keys (apps/grobase/scripts/env/generate-env.sh:52-63) — same header,
# same claims shape, same HMAC-SHA256. The signature is the RAW HMAC digest,
# base64url-encoded: `openssl dgst -hmac` prints a HEX digest, and a hex
# string is not a valid JWT signature — every key minted that way was
# rejected by PostgREST and GoTrue alike.
#
# Prints only the variable NAMES it wrote. Never a value.
#
# POSIX sh: the eval scripts must also run under a plain `sh` (the migrate
# guard test invokes `sh migrate.sh`).
set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
ENV_FILE="$HERE/.env"

# ---- refuse to overwrite ----
if [ -f "$ENV_FILE" ] && [ "${FORCE:-0}" != "1" ]; then
  echo "ERROR: $ENV_FILE already exists — refusing to overwrite (FORCE=1 overwrites)" >&2
  exit 1
fi

# ---- random values ----
# Alphanumeric only: the passwords travel in a DSN (PGRST_DB_URI) and in a
# psql \set, so no quoting/escaping surprises. Same shape as grobase's
# gen_alnum().
gen_alnum() {
  n=$1
  out=""
  while [ "${#out}" -lt "$n" ]; do
    out="${out}$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9')"
  done
  printf '%s' "$out" | cut -c1-"$n"
}

POSTGRES_PASSWORD=$(gen_alnum 32)
AUTHENTICATOR_PASSWORD=$(gen_alnum 32)
JWT_SECRET=$(openssl rand -hex 32)

# ---- HS256 JWTs ----
# base64url without line wrapping: `openssl base64 -A` (the wrapped default
# would put a newline in the middle of every segment).
b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }

# sign_jwt <role> — header and payload are base64url, the signature is
# HMAC-SHA256 over "header.payload" in RAW binary form.
sign_jwt() {
  role=$1
  iat=$(date +%s)
  exp=$((iat + 315360000))
  header='{"alg":"HS256","typ":"JWT"}'
  payload=$(printf '{"role":"%s","iss":"eval","iat":%s,"exp":%s}' "$role" "$iat" "$exp")
  h=$(printf '%s' "$header" | b64url)
  p=$(printf '%s' "$payload" | b64url)
  sig=$(printf '%s' "$h.$p" | openssl dgst -sha256 -mac HMAC -macopt "key:$JWT_SECRET" -binary | b64url)
  printf '%s.%s.%s' "$h" "$p" "$sig"
}

ANON_KEY=$(sign_jwt anon)
SERVICE_ROLE_KEY=$(sign_jwt service_role)

# ---- write .env (mode 600) ----
umask 077
tmp="$ENV_FILE.tmp.$$"
cat > "$tmp" <<EOF
# Auto-generated by gen-secrets.sh — never edit by hand, never commit.
# Mode 600. Regenerate with: FORCE=1 infrastructure/eval/gen-secrets.sh
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
AUTHENTICATOR_PASSWORD=$AUTHENTICATOR_PASSWORD
JWT_SECRET=$JWT_SECRET
ANON_KEY=$ANON_KEY
SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
EOF
chmod 600 "$tmp"
mv "$tmp" "$ENV_FILE"

# ---- print only the names ----
echo "wrote $ENV_FILE (mode 600) with:"
echo "POSTGRES_PASSWORD"
echo "AUTHENTICATOR_PASSWORD"
echo "JWT_SECRET"
echo "ANON_KEY"
echo "SERVICE_ROLE_KEY"
