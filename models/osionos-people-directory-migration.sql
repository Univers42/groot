-- osionos-people-directory-migration.sql
-- ---------------------------------------------------------------------------
-- TOMBSTONE. This file used to create public.osionos_people_directory: a view
-- over public.users, public.user_profiles and public.osionos_bridge_identities
-- that recomputed to_tsvector() per row, so every directory search was a
-- sequential scan over three tables (its own header called that out as a
-- "ponytail" note). The bridge reads the view with the service key, so the
-- view is the only path to the people directory.
--
-- WHAT REPLACED IT
--   models/osionos-account-profiles-migration.sql (ADR 0029). It creates the
--   view again, over public.osionos_profiles — a table with the profile's own
--   columns, a stored tsvector and GIN/trigram indexes — and keeps the old
--   column order, so the old bridge image's SELECT still works unchanged.
--   The view's NOTIFY pgrst moved with it: PostgREST would otherwise keep
--   serving the dropped view's OID.
--
-- WHY THIS FILE STAYS
--   A file that is gone takes its NOTIFY with it, and the runner's
--   alphabetical pass would have nothing to replay. An empty file is the
--   tombstone: it says what replaced it and why, and it creates nothing.
--   Nothing here re-creates the old view, so the directory has exactly one
--   definition.
-- ---------------------------------------------------------------------------
