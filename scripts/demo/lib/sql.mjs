// Renders the CRM mount's DDL and data from tables.mjs. Both files are applied by the mount's own
// role with `psql -1 -v ON_ERROR_STOP=1` (devil condition 4), so they carry no BEGIN/COMMIT and
// nothing needing a superuser. Rows insert with ON CONFLICT (id) DO NOTHING (condition 11): a
// re-run never overwrites what the demo user edited in the app.
import { TABLES } from './tables.mjs';
import { viewStatements } from './views.mjs';
import { centsText } from './prng.mjs';

// Below the 200 KB per-statement ceiling with room for one more row.
const CHUNK_BYTES = 150 * 1024;

export function literal(value, type) {
  if (value === null || value === undefined) return 'NULL';
  if (type === 'boolean') return value ? 'TRUE' : 'FALSE';
  if (type === 'integer') return String(value);
  if (type.startsWith('numeric')) return centsText(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

function columnDdl(column) {
  let out = `  ${column.name} ${column.type}`;
  if (column.name === 'id') return `${out} PRIMARY KEY`;
  if (!column.null) out += ' NOT NULL';
  if (column.unique) out += ' UNIQUE';
  if (column.fk) out += ` REFERENCES ${column.fk} (id)`;
  return out;
}

function tableDdl(table) {
  const parts = table.columns.map(columnDdl);
  table.checks.forEach((check, n) => parts.push(`  CONSTRAINT ${table.name}_check_${n + 1} CHECK (${check})`));
  for (const cols of table.uniques || []) parts.push(`  UNIQUE (${cols.join(', ')})`);
  const indexes = table.columns.filter((c) => c.fk && !c.unique)
    .map((c) => `CREATE INDEX IF NOT EXISTS ${table.name}_${c.name}_idx ON ${table.name} (${c.name});`);
  return [`CREATE TABLE IF NOT EXISTS ${table.name} (\n${parts.join(',\n')}\n);`, ...indexes].join('\n');
}

function header(kind, args) {
  return [
    `-- Arlet demo CRM mount: ${kind}. Generated by scripts/demo/generate.mjs; do not edit.`,
    `-- Target database demo_${args.uid8}_crm, anchor ${args.anchor}, seed ${args.seed}.`,
    '-- Apply as the mount role: psql -1 -v ON_ERROR_STOP=1 -f <this file>',
  ].join('\n');
}

export function renderSchema(args) {
  const ledger = '-- Filled by the loader (one row per applied file); the generator only creates it.\n' +
    'CREATE TABLE IF NOT EXISTS demo_schema (\n  file text PRIMARY KEY,\n  sha256 text NOT NULL\n);';
  const views = viewStatements(args.anchor).map(([name, body]) => `CREATE OR REPLACE VIEW ${name} AS\n${body};`);
  return `${[header('schema', args), ledger, ...TABLES.map(tableDdl), ...views].join('\n\n')}\n`;
}

function rowTuple(table, row) {
  return `(${table.columns.map((c) => literal(row[c.name], c.type)).join(', ')})`;
}

export function insertStatements(table, rows) {
  const head = `INSERT INTO ${table.name} (${table.columns.map((c) => c.name).join(', ')}) VALUES\n`;
  const tail = '\nON CONFLICT (id) DO NOTHING;';
  const statements = [];
  let tuples = [];
  let bytes = 0;
  for (const row of rows) {
    const tuple = rowTuple(table, row);
    const size = Buffer.byteLength(tuple) + 2;
    if (tuples.length > 0 && bytes + size > CHUNK_BYTES) {
      statements.push(head + tuples.join(',\n') + tail);
      tuples = [];
      bytes = 0;
    }
    tuples.push(tuple);
    bytes += size;
  }
  if (tuples.length > 0) statements.push(head + tuples.join(',\n') + tail);
  return statements;
}

export function dataStatementsFor(tables) {
  return TABLES.flatMap((table) => insertStatements(table, tables[table.name]));
}

export function renderData(args, tables) {
  return `${[header('data', args), ...dataStatementsFor(tables)].join('\n\n')}\n`;
}
